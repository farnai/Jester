# Cache for calculated weekly transits:
# Key: f"{user_id}:{iso_year}:{iso_week}:{data_ver}:{user_tz}"
_WEEKLY_CACHE: dict[str, dict[str, Any]] = {}

# Session unlock set for unlocked state during current runtime/session:
# Key: f"{user_id}:{iso_year}:{iso_week}"
_UNLOCKED_SESSIONS: set[str] = set()


def get_weekly_energy_content(archetype_id: str) -> dict[str, str]:
    """
    Returns the rich, deterministic Georgian weekly energy copy for a given archetype.
    """
    clean_id = archetype_id.lower().strip()
    return WEEKLY_ARCHETYPES_DATA.get(clean_id, WEEKLY_ARCHETYPES_DATA["neutral"])


def is_weekly_energy_unlocked(user_id: uuid.UUID | str, iso_year: int, iso_week: int) -> bool:
    """
    Checks if this user has unlocked this ISO calendar week.
    """
    key = f"{str(user_id)}:{iso_year}:{iso_week}"
    return key in _UNLOCKED_SESSIONS


def record_weekly_energy_unlock(user_id: uuid.UUID | str, iso_year: int, iso_week: int) -> None:
    """
    Marks this user's ISO calendar week as unlocked.
    """
    key = f"{str(user_id)}:{iso_year}:{iso_week}"
    _UNLOCKED_SESSIONS.add(key)
