def test_openai_provider_successful_invocation_and_normalization():
    mock_response = _create_mock_chat_completion(
        content="Architecture plan decomposed into 3 phases.\n\nPhase 1: Foundation.\nPhase 2: Adapters.",
        model="o3-mini-2026",
    )
    mock_client = MagicMock()
    mock_client.chat.completions.create.return_value = mock_response

    provider = OpenAIProvider(api_key="mock", client=mock_client)

    req = InvocationRequest(
        request_id="req-test-success",
        task_id="TASK-0004",
        role="architect",
        agent_id="chatgpt-lead",
        provider="openai",
        model="o3-mini",
        required_capabilities={"planning", "reasoning"},
        payload={"title": "Architect Feature", "goal": "Establish foundation"},
        created_at="2026-09-17T00:00:00Z",
    )

    result = provider.invoke(req)

    assert result.status == InvocationStatus.SUCCESS
    assert result.task_id == "TASK-0004"
    assert result.agent_id == "chatgpt-lead"
    assert result.provider == "openai"
    assert result.model == "o3-mini-2026"
    assert "Architecture plan decomposed" in result.summary
    assert result.error_message is None

    # Check raw metadata extraction and confirm zero SDK object leak
    assert result.raw_metadata["response_id"] == "chatcmpl-mock-12345"
    assert result.raw_metadata["prompt_tokens"] == 150
    assert result.raw_metadata["total_tokens"] == 190
    assert not hasattr(result, "choices")
    assert isinstance(result.raw_metadata, dict)

    # Verify mock client arguments
    mock_client.chat.completions.create.assert_called_once()
    call_kwargs = mock_client.chat.completions.create.call_args[1]
    assert call_kwargs["model"] == "o3-mini"
    messages = call_kwargs["messages"]
    assert len(messages) == 2
    assert messages[0]["role"] == "system"
    assert "software architect" in messages[0]["content"]
    assert messages[1]["role"] == "user"
    assert "TASK ID: TASK-0004" in messages[1]["content"]


