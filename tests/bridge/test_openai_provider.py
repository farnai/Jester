def test_bridge_core_openai_integration():
    """Validates that BridgeCore seamlessly orchestrates an OpenAIProvider."""
    mock_response = _create_mock_chat_completion(content="Decomposition completed: 2 tasks defined.")
    mock_client = MagicMock()
    mock_client.chat.completions.create.return_value = mock_response

    openai_provider = OpenAIProvider(api_key="mock", client=mock_client)

    config = BridgeConfig(
        role_bindings={"architect": "chatgpt-lead"},
        agents={
            "chatgpt-lead": AgentProfile(
                id="chatgpt-lead",
                role="architect",
                provider="openai",
                model="o3-mini",
                capabilities={"planning", "reasoning", "repository_read"},
            )
        },
    )

    core = BridgeCore(config=config, providers={"openai": openai_provider})

    task = Task(
        id="TASK-ARCH-01",
        title="Plan Architecture",
        role=Role.ARCHITECT.value,
        required_capabilities={"planning", "reasoning"},
        goal="Decompose system into modules",
    )

    result = core.dispatch(task)
    assert result.status == InvocationStatus.SUCCESS
    assert result.task_id == "TASK-ARCH-01"
    assert result.agent_id == "chatgpt-lead"
    assert result.provider == "openai"
    assert "Decomposition completed" in result.summary


