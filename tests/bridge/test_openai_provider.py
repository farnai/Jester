def _create_mock_chat_completion(
    content="This is a test response generated by the model.\n\nAdditional details here.",
    model="gpt-4o",
    prompt_tokens=150,
    completion_tokens=40,
    total_tokens=190,
    finish_reason="stop",
    response_id="chatcmpl-mock-12345",
):
    """Helper to build a mock ChatCompletion object mimicking OpenAI SDK response."""
    message = MagicMock()
    message.content = content

    choice = MagicMock()
    choice.message = message
    choice.finish_reason = finish_reason

    usage = MagicMock()
    usage.prompt_tokens = prompt_tokens
    usage.completion_tokens = completion_tokens
    usage.total_tokens = total_tokens

    response = MagicMock()
    response.id = response_id
    response.model = model
    response.choices = [choice]
    response.usage = usage
    return response


def test_openai_provider_construction_and_properties():
    provider = OpenAIProvider(
        api_key="test-key-mock",
        default_model="o3-mini",
        timeout=30.0,
        supported_capabilities={"planning", "reasoning", "repository_read"},
    )
    assert provider.provider_id == "openai"
    assert provider.default_model == "o3-mini"
    assert "planning" in provider.get_supported_capabilities()
    assert "repository_write" not in provider.get_supported_capabilities()
    assert provider.health_check() is True


